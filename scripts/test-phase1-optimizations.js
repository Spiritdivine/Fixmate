import http from 'http';
import app from '../src/app.js';
import prisma from '../src/config/db.js';

let server;
const PORT = 5098; // Dedicated port for isolated test run
const BASE_URL = `http://127.0.0.1:${PORT}`;

async function runTests() {
  console.log('🧪 Starting Phase 1 Performance & Caching Verification Tests...\n');

  let passed = 0;
  let failed = 0;

  async function assert(desc, fn) {
    try {
      await fn();
      console.log(`  ✅ PASS: ${desc}`);
      passed++;
    } catch (err) {
      console.error(`  ❌ FAIL: ${desc} -> ${err.message}`);
      failed++;
    }
  }

  // Helper HTTP request with headers inspection without client-side header contamination
  function fetchWithHeaders(path, headers = {}) {
    return new Promise((resolve, reject) => {
      const req = http.request(
        `${BASE_URL}${path}`,
        {
          method: 'GET',
          headers: {
            Accept: 'application/json',
            ...headers,
          },
        },
        (res) => {
          const chunks = [];
          res.on('data', (chunk) => chunks.push(chunk));
          res.on('end', () => {
            const body = Buffer.concat(chunks).toString();
            resolve({
              status: res.statusCode,
              headers: res.headers,
              body: res.statusCode === 304 ? null : body,
            });
          });
        }
      );
      req.on('error', reject);
      req.end();
    });
  }

  try {
    // 1. Boot test server
    await new Promise((resolve) => {
      server = app.listen(PORT, '127.0.0.1', () => {
        console.log(`📡 Temporary test server running at ${BASE_URL}`);
        resolve();
      });
    });

    // TEST 1: Compression on large payload
    await assert('Compression middleware returns compressed response for /api/v1/jobs/categories', async () => {
      const res = await fetchWithHeaders('/api/v1/jobs/categories', {
        'Accept-Encoding': 'gzip, deflate',
      });
      if (res.status !== 200) throw new Error(`Unexpected status ${res.status}`);
      const encoding = res.headers['content-encoding'];
      // If response body is > 1024 bytes, compression will activate
      const isCompressed = encoding === 'gzip' || encoding === 'br';
      if (!isCompressed && res.body && res.body.length > 1024) {
        throw new Error(`Expected content-encoding gzip/br but got: ${encoding}`);
      }
      console.log(`    (Content-Encoding: ${encoding || 'identity/uncompressed (<1KB)'})`);
    });

    // TEST 2: Cache-Control on Category Discovery
    await assert('HTTP Cache-Control header is set on /api/v1/jobs/categories', async () => {
      const res = await fetchWithHeaders('/api/v1/jobs/categories');
      const cacheControl = res.headers['cache-control'];
      if (!cacheControl || !cacheControl.includes('max-age=3600')) {
        throw new Error(`Expected max-age=3600 in Cache-Control, got: "${cacheControl}"`);
      }
      if (!cacheControl.includes('stale-while-revalidate=86400')) {
        throw new Error(`Expected stale-while-revalidate=86400, got: "${cacheControl}"`);
      }
    });

    // TEST 3: Cache-Control on Job Feed
    await assert('HTTP Cache-Control header is set on /api/v1/jobs', async () => {
      const res = await fetchWithHeaders('/api/v1/jobs');
      const cacheControl = res.headers['cache-control'];
      if (!cacheControl || !cacheControl.includes('max-age=30')) {
        throw new Error(`Expected max-age=30 in Cache-Control, got: "${cacheControl}"`);
      }
    });

    // TEST 4: Cache-Control on Artisan Discovery
    await assert('HTTP Cache-Control header is set on /api/v1/profiles/artisans', async () => {
      const res = await fetchWithHeaders('/api/v1/profiles/artisans');
      const cacheControl = res.headers['cache-control'];
      if (!cacheControl || !cacheControl.includes('max-age=60')) {
        throw new Error(`Expected max-age=60 in Cache-Control, got: "${cacheControl}"`);
      }
    });

    // TEST 5: Cache-Control on SEO Robots
    await assert('HTTP Cache-Control header is set on /robots.txt', async () => {
      const res = await fetchWithHeaders('/robots.txt');
      const cacheControl = res.headers['cache-control'];
      if (!cacheControl || !cacheControl.includes('max-age=86400')) {
        throw new Error(`Expected max-age=86400 in Cache-Control, got: "${cacheControl}"`);
      }
    });

    // TEST 6: ETag Generation and HTTP 304 Not Modified
    await assert('Server generates ETag and returns 304 Not Modified on If-None-Match', async () => {
      const firstRes = await fetchWithHeaders('/api/v1/jobs/categories');
      const etag = firstRes.headers['etag'];
      if (!etag) {
        throw new Error('ETag header was not generated by Express');
      }

      // Re-request with If-None-Match
      const secondRes = await fetchWithHeaders('/api/v1/jobs/categories', {
        'if-none-match': etag,
      });

      if (secondRes.status !== 304) {
        throw new Error(`Expected HTTP 304 Not Modified, got ${secondRes.status}`);
      }
      console.log(`    (ETag: ${etag} -> 304 Not Modified verified)`);
    });

    // TEST 7: Optimized Prisma Projections for Categories
    await assert('Category query returns structured schema without database errors', async () => {
      const res = await fetchWithHeaders('/api/v1/jobs/categories');
      const parsed = JSON.parse(res.body);
      if (!parsed.data || !Array.isArray(parsed.data)) {
        throw new Error('Expected data to be an array of categories');
      }
      if (parsed.data.length > 0) {
        const cat = parsed.data[0];
        if (cat.name === undefined || cat.slug === undefined) {
          throw new Error('Category object missing projected fields');
        }
      }
    });

    console.log(`\n========================================`);
    console.log(`Test Results: ${passed} Passed, ${failed} Failed`);
    console.log(`========================================\n`);

    if (failed > 0) {
      process.exit(1);
    }
  } catch (err) {
    console.error('Fatal testing error:', err);
    process.exit(1);
  } finally {
    if (server) {
      server.close();
    }
    await prisma.$disconnect().catch(() => {});
  }
}

runTests();
